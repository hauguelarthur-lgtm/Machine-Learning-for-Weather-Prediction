import torch
import numpy as np
import xarray as xr
from torch.utils.data import DataLoader, Subset
from datetime import datetime, timedelta
import json
import os

from dataset import MeteorologicalDataset
from architecture import ResUNet

def extract_latitudes(reference_file="./data/processed/engineered_1996.nc"):
    ds = xr.open_dataset(reference_file)
    lats = ds['latitude'].values
    ds.close()
    return lats

def get_climatology_slice(climatology_ds, current_time):
    """
    Extracts the exact 2D spatial baseline for the specific Day of Year and Hour.
    """
    day_of_year = current_time.timetuple().tm_yday
    # Ensure leap year compatibility (map day 366 to 365 if climatology lacks it)
    if day_of_year == 366 and 'dayofyear' in climatology_ds.dims and climatology_ds.dayofyear.size == 365:
        day_of_year = 365 
        
    hour = current_time.hour
    
    # Isolate the spatial slice: R^(C x Y x X)
    c_slice = climatology_ds.sel(dayofyear=day_of_year, hour=hour)
    
    # Cast to PyTorch tensor
    c_tensor = torch.from_numpy(c_slice.to_array().values).float()
    return c_tensor

def execute_wb2_evaluation():
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print("Initializing WB2 Offline ACC Evaluation...")

    # 1. Load Hardware Geometry and Weights
    lats = extract_latitudes()
    lat_rad = np.deg2rad(np.array(lats, dtype=np.float32))
    weights = np.cos(lat_rad)
    weights_normalized = weights / np.mean(weights)
    
    # Shape: (1, 1, 64, 1) to broadcast across (Batch, Channel, Lat, Lon)
    W = torch.tensor(weights_normalized, device=device).view(1, 1, len(lats), 1)

    # 2. Reconstruct Model Topology
    model = ResUNet(in_channels=102, out_channels=102).to(device)
    
    # Target the optimal checkpoint generated by train_convergence.py
    checkpoint_path = "./models/checkpoints/resunet_best_epoch_X.pth" # Update 'X' dynamically
    if not os.path.exists(checkpoint_path):
        raise FileNotFoundError(f"Checkpoint missing at {checkpoint_path}")
        
    checkpoint = torch.load(checkpoint_path, map_location=device)
    model.load_state_dict(checkpoint['model_state_dict'])
    model.eval()

    # 3. I/O Stream Initialization
    full_dataset = MeteorologicalDataset(tensor_dir="./data/processed/tensors/", horizon=1)
    
    # Define validation temporal bounds (2020-2021)
    train_end_idx = 35064
    val_end_idx = train_end_idx + (2 * 1460)
    test_subset = Subset(full_dataset, range(train_end_idx, val_end_idx))
    
    test_loader = DataLoader(test_subset, batch_size=16, shuffle=False, num_workers=4)
    
    # 4. Climatology Lookup Initialization
    print("Loading 1990-2019 Dask Climatology...")
    climatology_ds = xr.open_dataset("./data/processed/evaluation/wb2_climatology_baseline.nc")
    
    # Define the absolute start time of the validation subset
    # Assumes data blocks start sequentially at 1996-01-01 00:00:00
    current_time = datetime(2020, 1, 1, 0, 0, 0)
    time_step = timedelta(hours=6)

    # 5. Global Covariance Accumulators
    C = 102 # Channel depth
    sum_weighted_cov = torch.zeros(C, device=device)
    sum_weighted_var_P = torch.zeros(C, device=device)
    sum_weighted_var_T = torch.zeros(C, device=device)

    print("Executing spatiotemporal convolution over test matrix...")
    with torch.no_grad():
        for batch_idx, (P_input, T_target) in enumerate(test_loader):
            P_input = P_input.to(device)
            T_target = T_target.to(device)
            
            # Execute physical inference mapping
            with torch.amp.autocast('cuda'):
                P_pred = model(P_input)
            
            batch_size = P_pred.shape[0]
            
            # Construct the dynamic climatology batch
            c_batch_list = []
            for b in range(batch_size):
                # The target state T is +1 horizon ahead of the input state
                target_time = current_time + (full_dataset.horizon * time_step)
                c_slice = get_climatology_slice(climatology_ds, target_time)
                c_batch_list.append(c_slice)
                
                # Increment continuous temporal state
                current_time += time_step
                
            # Stack into R^(B x C x Y x X)
            C_baseline = torch.stack(c_batch_list).to(device)
            
            # Calculate anomalies
            P_prime = P_pred - C_baseline
            T_prime = T_target - C_baseline
            
            # Accumulate spatial integrals
            # sum over Batch (dim 0), Lat (dim 2), Lon (dim 3) -> yields 1D tensor of length C
            sum_weighted_cov += torch.sum(W * P_prime * T_prime, dim=(0, 2, 3))
            sum_weighted_var_P += torch.sum(W * (P_prime ** 2), dim=(0, 2, 3))
            sum_weighted_var_T += torch.sum(W * (T_prime ** 2), dim=(0, 2, 3))

    # 6. Final ACC Mathematical Reduction
    acc = sum_weighted_cov / torch.sqrt(sum_weighted_var_P * sum_weighted_var_T)
    acc = acc.cpu().numpy()
    
    # Output definitive scores
    with open("./data/processed/tensors/channel_ordering.json", "r") as f:
        channel_names = json.load(f)
        
    print("\nWeatherBench 2 Final Anomaly Correlation Coefficients:")
    for i, name in enumerate(channel_names):
        print(f"  {name}: {acc[i]:.4f}")

if __name__ == "__main__":
    execute_wb2_evaluation()